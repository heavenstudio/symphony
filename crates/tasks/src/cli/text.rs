//! How the board reads in a terminal.

use crate::sys::local_minute;
use crate::{Message, STATUSES, Task};
use std::collections::{BTreeMap, BTreeSet};

/// `role handle, …`: who holds a task.
pub fn roles_text(task: &Task) -> String {
    let held: Vec<String> = task
        .roles
        .iter()
        .map(|r| format!("{} {}", r.role, r.handle))
        .collect();
    held.join(", ")
}

/// `rows` laid out as columns two spaces apart, each as wide as its widest cell, the last one
/// unpadded: a table whose first row is its header.
pub fn columns(rows: &[Vec<String>]) -> Vec<String> {
    let count = rows.iter().map(Vec::len).max().unwrap_or(0);
    let widths: Vec<usize> = (0..count)
        .map(|at| {
            rows.iter()
                .filter_map(|row| row.get(at))
                .map(|cell| cell.chars().count())
                .max()
                .unwrap_or(0)
        })
        .collect();
    rows.iter()
        .map(|row| {
            let cells: Vec<String> = row
                .iter()
                .zip(&widths)
                .map(|(cell, width)| format!("{cell:<width$}"))
                .collect();
            cells.join("  ").trim_end().to_string()
        })
        .collect()
}

/// `docs/SPEC.md#Jump` → `[[SPEC#Jump]]`, the form the Symphony renders as a link.
pub fn wikilink(link: &str) -> String {
    let (path, heading) = link.split_once('#').unwrap_or((link, ""));
    let path = path
        .strip_prefix("docs/")
        .and_then(|p| p.strip_suffix(".md"))
        .unwrap_or(path);
    if heading.is_empty() {
        format!("[[{path}]]")
    } else {
        format!("[[{path}#{heading}]]")
    }
}

/// A thread line of `show`: `[2026-10-07 14:05] amber-heron to owner (msg): text`.
pub fn message_line(m: &Message) -> String {
    let to = m
        .recipient
        .as_deref()
        .filter(|r| !r.is_empty())
        .map(|r| format!(" to {r}"))
        .unwrap_or_default();
    format!(
        "[{}] {}{to} ({}): {}",
        local_minute(m.ts),
        m.sender,
        m.kind,
        m.text
    )
}

/// The word an inbox line of a message of `kind` starts with: `MSG`, `VERDICT`, and `MOVE` for the
/// one record line an inbox carries, the owner's move (`Store::inbox`).
pub fn event_kind(kind: &str) -> String {
    match kind {
        "system" => "MOVE".into(),
        kind => kind.to_uppercase(),
    }
}

/// A message as the inbox and the monitor print it, on one line.
pub fn event(m: &Message) -> String {
    let text = m.text.replace('\n', " ");
    if m.kind != "msg" {
        return format!(
            "{} {} from {} — {text}",
            event_kind(&m.kind),
            m.slug,
            m.sender
        );
    }
    let to = m
        .recipient
        .as_deref()
        .filter(|r| !r.is_empty())
        .map(|r| format!(" to {r}"))
        .unwrap_or_default();
    format!("MSG {} from {}{to} — {text}", m.slug, m.sender)
}

/// `tasks` as (depth, task) with each child right under its parent, at any depth. A task whose parent
/// is not in `tasks` (a filtered list) stands at the top; the order within a level is kept.
pub fn tree_order(tasks: &[Task]) -> Vec<(usize, &Task)> {
    let mut present: BTreeSet<&str> = BTreeSet::new();
    present.extend(tasks.iter().map(|t| t.slug.as_str()));
    let mut below: BTreeMap<&str, Vec<&Task>> = BTreeMap::new();
    for t in tasks {
        if let Some(parent) = t.parent.as_deref().filter(|p| present.contains(p)) {
            below.entry(parent).or_default().push(t);
        }
    }
    fn walk<'a>(
        t: &'a Task,
        depth: usize,
        below: &BTreeMap<&str, Vec<&'a Task>>,
        out: &mut Vec<(usize, &'a Task)>,
    ) {
        out.push((depth, t));
        for child in below.get(t.slug.as_str()).into_iter().flatten() {
            walk(child, depth + 1, below, out);
        }
    }
    let mut out = Vec::new();
    for t in tasks {
        if !t.parent.as_deref().is_some_and(|p| present.contains(p)) {
            walk(t, 0, &below, &mut out);
        }
    }
    out
}

/// The first line of every snapshot [`export_markdown`] writes, by which an export under the board
/// recipe knows a file it may replace.
pub const SNAPSHOT_TITLE: &str = "# Task board snapshot";

/// A readable snapshot of the board, for history; the live board is the store.
pub fn export_markdown(tasks: &[Task], now: f64) -> String {
    let mut lines = vec![
        SNAPSHOT_TITLE.to_string(),
        String::new(),
        format!(
            "Generated by `just tasks export` at {}. The live board is `just tasks list` and the Tasks page of `just symphony`; this file is a record, not the source.",
            local_minute(now)
        ),
        String::new(),
    ];
    for status in STATUSES {
        let group: Vec<&Task> = tasks.iter().filter(|t| t.status == status).collect();
        if group.is_empty() {
            continue;
        }
        lines.push(format!("## {status}"));
        lines.push(String::new());
        for t in group {
            let mut extra = Vec::new();
            if !t.roles.is_empty() {
                extra.push(roles_text(t));
            }
            if !t.links.is_empty() {
                let links: Vec<String> = t.links.iter().map(|l| wikilink(l)).collect();
                extra.push(links.join(" "));
            }
            if !t.depends.is_empty() {
                let after: Vec<String> = t.depends.iter().map(|d| format!("**{d}**")).collect();
                extra.push(format!("after {}", after.join(", ")));
            }
            let extra: String = extra.iter().map(|e| format!(" · {e}")).collect();
            lines.push(format!(
                "- **{}** — {} (p{}){extra}",
                t.slug, t.title, t.priority
            ));
        }
        lines.push(String::new());
    }
    lines.join("\n")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn columns_are_as_wide_as_their_widest_cell_and_the_last_is_unpadded() {
        let rows = |cells: &[&[&str]]| -> Vec<Vec<String>> {
            cells
                .iter()
                .map(|row| row.iter().map(|cell| cell.to_string()).collect())
                .collect()
        };
        assert_eq!(
            columns(&rows(&[
                &["HANDLE", "KIND", "ROLES"],
                &["amber-heron", "worker", "sim/a(executor)"],
                &["  é-kid", "reviewer", ""],
            ])),
            [
                "HANDLE       KIND      ROLES",
                "amber-heron  worker    sim/a(executor)",
                "  é-kid      reviewer",
            ]
        );
        assert!(columns(&[]).is_empty());
    }

    #[test]
    fn an_event_names_its_kind_and_the_owners_move_reads_as_a_move() {
        let line = |kind: &str, recipient: Option<&str>, text: &str| {
            event(&Message {
                id: 7,
                slug: "tools/x".into(),
                sender: "owner".into(),
                recipient: recipient.map(str::to_string),
                kind: kind.into(),
                text: text.into(),
                ts: 0.0,
            })
        };
        assert_eq!(
            line("msg", Some("@executor"), "stop\nnow"),
            "MSG tools/x from owner to @executor — stop now"
        );
        assert_eq!(line("msg", Some(""), "hi"), "MSG tools/x from owner — hi");
        assert_eq!(
            line("verdict", None, "approve: ok"),
            "VERDICT tools/x from owner — approve: ok"
        );
        assert_eq!(
            line("system", None, "owner moved it review → cancelled"),
            "MOVE tools/x from owner — owner moved it review → cancelled"
        );
        assert_eq!(event_kind("system"), "MOVE");
        assert_eq!(event_kind("ask"), "ASK", "any other kind is its own word");
    }

    #[test]
    fn a_link_into_docs_is_a_wikilink_and_any_other_kept_whole() {
        assert_eq!(wikilink("docs/SPEC.md#Jump"), "[[SPEC#Jump]]");
        assert_eq!(wikilink("docs/game/SPEC.md"), "[[game/SPEC]]");
        assert_eq!(wikilink("notes.md"), "[[notes.md]]");
        assert_eq!(wikilink("docs/X.md#"), "[[X]]");
        assert_eq!(wikilink("docs/data/x.json#k"), "[[docs/data/x.json#k]]");
    }
}
